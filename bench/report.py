#!/usr/bin/env python3
"""The published benchmark page (BEN-12): docs/benchmarks.md and its charts, written from
stored A/B results, so the README, the comparison page and the launch all quote one source.
Standard library only.

    python3 -I bench/report.py bench/results/<date>/runs.jsonl [--out docs] [--readme README.md]
    python3 -I bench/report.py --check [--out docs]    # regenerate and compare, byte for byte

Every arm is shown, including the ones that lose. Cost per passed task, pass rate and
turns sit side by side, never folded into one score. Charts are hand-written SVG bars with
interval whiskers. The output depends only on the results, the baseline, the number of
bootstrap resamples and the seed, all named in the page's first line, so `--check` can
rebuild the page from it and fail when anything differs.
`--readme` rewrites the block between `<!-- benchmarks:start -->` and
`<!-- benchmarks:end -->` with the same headline numbers.
"""
import argparse
import json
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
sys.path.insert(0, HERE)
import stats  # noqa: E402

HEADER = "<!-- generated by bench/report.py from {results} (baseline {baseline}, {resamples} resamples, seed {seed}); edit the results, not this page -->"
HEADER_RE = re.compile(r"^<!-- generated by bench/report\.py from (\S+) \(baseline (\S+), (\d+) resamples, seed (\d+)\)")
START, END = "<!-- benchmarks:start -->", "<!-- benchmarks:end -->"


def load(path):
    with open(path) as f:
        return [json.loads(line) for line in f if line.strip()]


def headline(rows, baseline, resamples, seed):
    """Per arm: pass rate with its interval, cost per passed task, median turns, and the
    cost and turns ratios to the baseline with their intervals."""
    runs = [r for r in rows if r.get("kind", "run") == "run" and r.get("status") != "rate_limited"]
    arms = sorted({r["arm"] for r in runs}, key=lambda a: (a != baseline, a))
    ratios = {m: {a["arm"]: a for a in stats.compare(runs, m, baseline, resamples, seed)["arms"]}
              for m in ("cost_usd", "turns")}
    out = []
    for arm in arms:
        x = stats.arm_summary([r for r in runs if r["arm"] == arm])
        out.append({"arm": arm, "passed": x["passed"], "runs": x["runs"], "pass_rate": x["passed"] / x["runs"],
                    "pass_interval": x["pass_interval"], "cost_per_pass": x["cost_per_pass"], "turns": x["turns"],
                    "exercised": x["exercised"],
                    "cost_ratio": ratios["cost_usd"][arm].get("ratio"), "cost_interval": ratios["cost_usd"][arm].get("interval"),
                    "turns_ratio": ratios["turns"][arm].get("ratio"), "turns_interval": ratios["turns"][arm].get("interval")})
    return out


def ratio_cell(value, interval):
    if value is None:
        return "–"
    return f"{value:.2f} ({interval[0]:.2f}–{interval[1]:.2f})"


def headline_table(items, baseline):
    lines = ["| arm | passed (95%) | cost per passed task | turns (median) | cost ÷ baseline (95%) | turns ÷ baseline (95%) |",
             "|---|---|---:|---:|---|---|"]
    for x in items:
        lo, hi = x["pass_interval"]
        cost = "–" if x["cost_per_pass"] is None else f"${x['cost_per_pass']:.4f}"
        turns = "–" if x["turns"] is None else f"{x['turns']:g}"
        if x["arm"] == baseline:
            cost_r = turns_r = "(baseline)"
        else:
            cost_r = ratio_cell(x["cost_ratio"], x["cost_interval"])
            turns_r = ratio_cell(x["turns_ratio"], x["turns_interval"])
            if x["exercised"] is not None and x["exercised"] < stats.EXERCISED:
                cost_r += " ⚠ not exercised"
        lines.append(f"| {x['arm']} | {x['passed']}/{x['runs']} ({lo:.0%}–{hi:.0%}) | {cost} | {turns} | {cost_r} | {turns_r} |")
    return "\n".join(lines)


def svg_bars(title, items, axis_max, reference=None, percent=False):
    """Horizontal bars with interval whiskers: items are (label, value, low, high)."""
    left, plot, row, top = 170, 400, 30, 40
    height = top + row * len(items) + 30
    x = lambda v: left + plot * min(max(v, 0), axis_max) / axis_max
    label = (lambda v: f"{v * 100:.0f}%") if percent else (lambda v: f"{v:.2f}")
    out = [f'<svg xmlns="http://www.w3.org/2000/svg" width="{left + plot + 80}" height="{height}" '
           f'font-family="system-ui, sans-serif" font-size="13">',
           f'<title>{title}</title>',
           f'<text x="10" y="22" font-weight="bold">{title}</text>']
    axis_y = top + row * len(items) + 4
    if reference is not None:   # under the bars and labels
        out.append(f'<line x1="{x(reference):.1f}" y1="{top}" x2="{x(reference):.1f}" y2="{axis_y}" '
                   f'stroke="#c00" stroke-dasharray="4 3"/>')
    for i, (name, value, lo, hi) in enumerate(items):
        y = top + i * row
        out.append(f'<text x="{left - 8}" y="{y + 18}" text-anchor="end">{name}</text>')
        if value is None:
            out.append(f'<text x="{left + 4}" y="{y + 18}" fill="#666">no data</text>')
            continue
        out.append(f'<rect x="{left}" y="{y + 6}" width="{x(value) - left:.1f}" height="16" fill="#4c78a8"/>')
        if lo is not None and hi is not None:
            mid = y + 14
            out.append(f'<line x1="{x(lo):.1f}" y1="{mid}" x2="{x(hi):.1f}" y2="{mid}" stroke="#222" stroke-width="1.5"/>')
            for end in (lo, hi):
                out.append(f'<line x1="{x(end):.1f}" y1="{mid - 6}" x2="{x(end):.1f}" y2="{mid + 6}" stroke="#222" stroke-width="1.5"/>')
        out.append(f'<text x="{max(x(value), x(hi) if hi is not None else 0) + 6:.1f}" y="{y + 18}">{label(value)}</text>')
    out.append(f'<line x1="{left}" y1="{axis_y}" x2="{left + plot}" y2="{axis_y}" stroke="#999"/>')
    for tick in (0, axis_max / 2, axis_max):
        out.append(f'<text x="{x(tick):.1f}" y="{axis_y + 16}" text-anchor="middle" fill="#666">{label(tick)}</text>')
    out.append("</svg>")
    return "\n".join(out) + "\n"


def axis_for(values):
    """A round axis end above every value, at least 1.5 so the 1.0 line sits inside."""
    top = max([v for v in values if v is not None] + [1.0]) * 1.1
    for end in (1.5, 2, 3, 4, 5, 10, 20, 50, 100):
        if top <= end:
            return end
    return top


def build(results, baseline="baseline", resamples=10_000, seed=1):
    """{file name: content} of the page and its charts."""
    rows = load(os.path.join(ROOT, results))
    items = headline(rows, baseline, resamples, seed)
    charts = {
        "benchmarks/pass-rate.svg": svg_bars(
            "Passed runs (Wilson 95%)", [(x["arm"], x["pass_rate"], *x["pass_interval"]) for x in items], 1.0, percent=True),
    }
    for key, title in (("cost", "Cost ÷ baseline (95%)"), ("turns", "Turns ÷ baseline (95%)")):
        bars = [(x["arm"], x[f"{key}_ratio"], *(x[f"{key}_interval"] or (None, None))) for x in items if x["arm"] != baseline]
        axis = axis_for([b[3] for b in bars] + [b[1] for b in bars])
        charts[f"benchmarks/{key}-ratio.svg"] = svg_bars(title, bars, axis, reference=1.0)
    body = stats.report(rows, baseline, resamples, seed).split("\n", 2)[2]   # without its own title
    page = "\n".join([
        HEADER.format(results=results, baseline=baseline, resamples=resamples, seed=seed),
        "# Benchmarks", "",
        "Every arm is shown, including the ones that lose. Cost per passed task, pass rate and turns are separate numbers, "
        "never one score. Ratios below 1 mean the arm used less than the baseline; the intervals are 95%.", "",
        headline_table(items, baseline), "",
        "![Passed runs](benchmarks/pass-rate.svg)", "",
        "![Cost compared with the baseline](benchmarks/cost-ratio.svg)", "",
        "![Turns compared with the baseline](benchmarks/turns-ratio.svg)", "",
        body.rstrip("\n"), "",
    ])
    return {"benchmarks.md": page, **charts}


def readme_block(page):
    """The README's numbers: the headline table, taken from the page so the two stay equal."""
    table = page.split("\n\n", 3)[2]
    return f"{START}\n{table}\n\nFrom [docs/benchmarks.md](docs/benchmarks.md), with intervals and every metric.\n{END}"


def write(files, out):
    for name, content in files.items():
        path = os.path.join(out, name)
        os.makedirs(os.path.dirname(path), exist_ok=True)
        with open(path, "w") as f:
            f.write(content)


def check(out):
    """Rebuild the page from the results its first line names; 1 if any file differs."""
    page = os.path.join(out, "benchmarks.md")
    if not os.path.exists(page):
        print(f"report: no {page} yet: nothing published to check")
        return 0
    with open(page) as f:
        m = HEADER_RE.match(f.readline())
    if not m:
        print(f"report: {page} wasn't written by bench/report.py")
        return 1
    results, baseline, resamples, seed = m.group(1), m.group(2), int(m.group(3)), int(m.group(4))
    differs = []
    for name, content in build(results, baseline, resamples, seed).items():
        try:
            with open(os.path.join(out, name)) as f:
                same = f.read() == content
        except OSError:
            same = False
        if not same:
            differs.append(name)
    if differs:
        print(f"report: {', '.join(differs)} differ from what {results} gives: rerun bench/report.py {results}")
        return 1
    print(f"report: {page} matches {results}")
    return 0


def main(argv):
    p = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    p.add_argument("results", nargs="?", help="a runs.jsonl, as a path from the repository root")
    p.add_argument("--out", default=os.path.join(ROOT, "docs"))
    p.add_argument("--baseline", default="baseline")
    p.add_argument("--resamples", type=int, default=10_000)
    p.add_argument("--seed", type=int, default=1)
    p.add_argument("--readme", help="a README whose benchmarks block to rewrite")
    p.add_argument("--check", action="store_true")
    args = p.parse_args(argv)
    if args.check:
        return check(args.out)
    if not args.results:
        p.error("give a results file, or --check")
    files = build(args.results, args.baseline, args.resamples, args.seed)
    write(files, args.out)
    if args.readme:
        with open(args.readme) as f:
            text = f.read()
        if START not in text or END not in text:
            print(f"report: {args.readme} has no {START} … {END} block", file=sys.stderr)
            return 2
        before, rest = text.split(START, 1)
        after = rest.split(END, 1)[1]
        with open(args.readme, "w") as f:
            f.write(before + readme_block(files["benchmarks.md"]) + after)
    print(f"report: wrote {', '.join(sorted(files))} to {args.out}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
